#!/usr/bin/env python3
# Generates src/sci-vm/src/trigonometry.{hpp,cpp}: sin and cos of whole
# degrees as the kernel functions compute them, sin(angle * M_PI / 180.0),
# for angles from -360 to 360. The values are those of the C library of the
# reference platform (glibc on x86-64, where the reference ScummVM runs), so
# that the interpreter matches the reference on every platform (spec section
# 5.3). Run it inside the toolchain container:
#
#   docker/run.sh python3 scripts/gen-trigonometry.py
import math
import os

LO, HI = -360, 360
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "sci-vm", "src")


def table(function):
    values = [function(a * math.pi / 180.0).hex() for a in range(LO, HI + 1)]
    return "\n".join("    " + ", ".join(values[i:i + 4]) + "," for i in range(0, len(values), 4))


header = """// SPDX-License-Identifier: GPL-3.0-or-later
//
// sin and cos of whole degrees, as ScummVM computes them in the kernel
// functions (sin(angle * M_PI / 180.0)), but the same on every platform
// (spec section 5.3): for angles from -360 to 360 the values come from a
// table of the reference platform's results (scripts/gen-trigonometry.py);
// other angles use the C library.

#pragma once

namespace sci::vm {

[[nodiscard]] double sin_degrees(int angle);
[[nodiscard]] double cos_degrees(int angle);

} // namespace sci::vm
"""

source = f"""// SPDX-License-Identifier: GPL-3.0-or-later
//
// Generated by scripts/gen-trigonometry.py: sin and cos of the double
// angle * M_PI / 180.0 for angles from {LO} to {HI}, as glibc on x86-64
// computes them. Other angles use the value of the angle modulo 360, which
// may differ from glibc's in the last bits (docs/ASSUMPTIONS.md).

#include "trigonometry.hpp"

#include <array>
#include <cstddef>

namespace sci::vm {{

namespace {{

constexpr int first_angle = {LO};
constexpr int last_angle = {HI};

constexpr std::array<double, {HI - LO + 1}> sin_table = {{
{table(math.sin)}
}};

constexpr std::array<double, {HI - LO + 1}> cos_table = {{
{table(math.cos)}
}};

std::size_t index(int angle) {{
    if (angle < first_angle || angle > last_angle) {{
        angle %= 360;
    }}
    return static_cast<std::size_t>(angle - first_angle);
}}

}} // namespace

double sin_degrees(int angle) {{
    return sin_table[index(angle)];
}}

double cos_degrees(int angle) {{
    return cos_table[index(angle)];
}}

}} // namespace sci::vm
"""

with open(os.path.join(root, "trigonometry.hpp"), "w") as f:
    f.write(header)
with open(os.path.join(root, "trigonometry.cpp"), "w") as f:
    f.write(source)
